REFERENCIA = "ASME B36.10M / ASME B36.19M"


class ErrorTuberia(ValueError):
    pass


def texto_nps(nps: float) -> str:
    """0.125 -> 1/8\", 1.5 -> 1 1/2\"."""
    fr = {0.125: "1/8", 0.25: "1/4", 0.5: "1/2", 0.75: "3/4"}
    entero = int(nps)
    resto = round(nps - entero, 3)
    if resto == 0:
        return f'{entero}"'
    frac = fr.get(resto, f"{resto:g}")
    return f'{frac}"' if entero == 0 else f'{entero} {frac}"'


def cedulas_de(nps: float) -> list[str]:
    return [c for c in CEDULAS if c in _T.get(nps, {})]


def espesor(nps: float, cedula: str) -> float:
    try:
        return _T[nps][cedula]
    except KeyError:
        raise ErrorTuberia(f"La cédula {cedula} no está definida para {texto_nps(nps)} "
                           f"en {REFERENCIA}. Elija otra cédula.") from None


def diametro_interior(nps: float, cedula: str) -> float:
    return OD_MM[nps] - 2 * espesor(nps, cedula)


def area_interior(nps: float, cedula: str) -> float:
    """Área interior [mm²] = π/4·DI²."""
    return math.pi / 4 * diametro_interior(nps, cedula) ** 2


def cedula_para(nps: float, cedula: str) -> str | None:
    """La cédula pedida si la norma la define para ese diámetro; si no, STD (o la primera definida). None si
    el diámetro no figura en la tabla."""
    ced = cedulas_de(nps)
    if not ced:
        return None
    return cedula if cedula in ced else ("STD" if "STD" in ced else ced[0])


def texto_cedula(cedula: str) -> str:
    """«Sch 40» para las cédulas numéricas; STD, XS, XXS y las «S» tal cual."""
    return f"Sch {cedula}" if cedula.isdigit() else cedula


def salida_valvula(nps_valvula: float, cedula: str) -> tuple[float, str] | None:
    """Área de la salida de la válvula [mm²] y cédula usada: diámetro de la válvula con la cédula de la tubería
    de salida (o la STD si esa cédula no existe para el diámetro de la válvula)."""
    ced = cedula_para(nps_valvula, cedula)
    return (area_interior(nps_valvula, ced), ced) if ced else None
